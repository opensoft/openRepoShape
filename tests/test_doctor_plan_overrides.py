#: The path a confident rule (`spec-governance`) puts in the spec leg.
DOCS = "docs/"
DOCS_IN_CODE = "code/docs/"
DOCS_RULE = "spec-governance"
#: Why the plans below answered `docs/` into the code leg.
DOCS_ANSWER = "the docs are generated by the code's build"
INDEX = "docs/index.md"
GUIDE = "docs/guide.md"
BLOB = "100644"
COMPLIANT = "COMPLIANT"
#: What L1-59 says, in the block `execute` writes and in the validator.
LATER = ("A directory's row answers for every file under it, one added "
         "after the adoption too")


def leg_entry(row: dict, role: str) -> dict:
    """The placement row's entry for one leg."""
    return next(leg for leg in row["detail"]["legs"] if leg["role"] == role)


def said(text: str) -> str:
    """`text` as a reader reads it wrapped: each line's comment marker
    dropped and its whitespace folded."""
    return " ".join(word for line in text.splitlines()
                    for word in line.strip().lstrip("#").split())


# --- L1-57: the doctor takes a recorded answer against a rule --------------

def test_an_answer_against_a_rule_is_not_misplaced_in_its_leg(standard,
                                                              project):
    """`code/docs/` is spec by `spec-governance`, so MISPLACED; a row
    answering `docs/` into the code leg is the plan's answer against that
    rule, and the doctor takes it there: `ok`, COMPLIANT, the path listed
    under `answered_paths` with the rule it overrode, and said."""
    stage(project / "code", INDEX, "# Docs\n")
    found = placement(standard, project)[2]
    assert [item["path"] for item in found["detail"]["misplaced"]] == [
        DOCS_IN_CODE], found["detail"]
    record_answers(project, (DOCS, "code", DOCS_ANSWER))
    result, verdict, row = placement(standard, project)
    assert result.returncode == 0, result.stdout + result.stderr
    assert (verdict, row["status"], row["detail"]["misplaced"]) == (
        COMPLIANT, "ok", []), row
    [answered] = row["detail"]["answered_paths"]
    assert (answered["path"], answered["classified_as"], answered["rule"],
            answered["recorded_leg"], answered["answered_by"],
            answered["resolution"], answered["confidence"]) == (
        DOCS_IN_CODE, "spec", DOCS_RULE, "code", [DOCS], DOCS_ANSWER,
        "recorded"), answered
    assert ("project.yaml's `answered_paths:` answers 1 path(s) into the "
            "leg they are in, which a rule puts elsewhere (#655): code/docs/ "
            "(spec by rule spec-governance)") in row["reason"], row["reason"]
    assert leg_entry(row, "code")["misplaced"] == 0
    assert row["next"] is None, row


@pytest.mark.parametrize("rows, staged", [
    (((DOCS, "spec", DOCS_ANSWER),), (INDEX,)),
    (((INDEX, "code", DOCS_ANSWER),), (INDEX, GUIDE)),
], ids=["a-row-for-the-other-leg", "one-file-of-two-answered"])
def test_an_answer_against_a_rule_settles_only_its_own_files_in_its_leg(
        standard, project, rows, staged):
    """RECORDS CONFER NOTHING, AND A PATH IS ANSWERED FILE BY FILE. A row
    naming the spec leg asserts nothing about the code leg's `docs/`, and a
    row for one file leaves its sibling in the wrong leg: both stay
    MISPLACED, exactly as with no record."""
    for name in staged:
        stage(project / "code", name, "# Docs\n")
    record_answers(project, *rows)
    result, verdict, row = placement(standard, project)
    assert result.returncode == 1, result.stdout + result.stderr
    assert verdict == "MISPLACED (1 path)"
    assert [item["path"] for item in row["detail"]["misplaced"]] == [
        DOCS_IN_CODE], row["detail"]
    assert "answered_paths" not in row["detail"], row["detail"]


# --- L1-57: the record `execute` writes -------------------------------------

#: A source whose `docs/` a rule calls spec, beside paths the rules call
#: code and root.
SOURCE_TREE = tree_of(
    ("README.md", BLOB), (INDEX, BLOB), (GUIDE, BLOB),
    ("src/app/util.py", BLOB), (".specify/memory/notes.md", BLOB))
SOURCE_COMMIT = "cd" * 20


@pytest.mark.parametrize("answers, rows", [
    ({DOCS: "code"}, [(DOCS, "code")]),
    ({DOCS: "spec"}, []),
    ({DOCS: "root"}, []),
    ({DOCS: "drop"}, []),
    ({INDEX: "code", GUIDE: "spec"}, [(INDEX, "code")]),
    ({"src/": "spec"}, [("src/", "spec")]),
    ({".specify/": "code"}, [(".specify/", "code")]),
], ids=["a-spec-rule-answered-code", "answered-as-the-rule-says",
        "answered-root", "answered-drop", "split-by-hand-half-against",
        "a-code-rule-answered-spec", "a-root-rule-answered-into-a-leg"])
def test_execute_records_each_answer_against_a_rule_into_a_leg(
        standard, answers, rows):
    """ONE ROW PER ENTRY KEPT IN A LEG THAT COVERS A PATH THE POLICY'S WALK
    PUTS ELSEWHERE, as for one it leaves a question (#525): a rule's other
    leg or the root. An entry answered as its rule says needs no record; one
    answered `root` or `drop` is in no leg; an entry split by hand is
    recorded only for the half answered against the rule."""
    adopt = adoption_module(standard)
    legs = {DOCS: "spec", "src/": "code", ".specify/": "root", **answers}
    if INDEX in answers:
        del legs[DOCS]
    entries = [{"path": path, "leg": leg, "resolution": f"why {leg}"}
               for path, leg in legs.items()]
    entries.append({"path": "README.md", "leg": "root"})
    block = adopt.answered_path_record(adopt.PathPolicy.load(
        adopt.PATH_POLICY), entries, SOURCE_TREE, SOURCE_COMMIT)
    recorded = parse_yaml(block)["answered_paths"] if block else []
    assert [(row["path"], row["leg"]) for row in recorded] == rows
    assert [row["resolution"] for row in recorded] == [
        f"why {leg}" for _, leg in rows], recorded


# --- L1-57, end to end: `execute`, then the doctor --------------------------

@pytest.fixture(scope="module")
def adopted_against_a_rule(standard, tmp_path_factory) -> dict:
    """`docs/` answered into the code leg against `spec-governance`,
    `examples/` into the spec leg, and the rules into the code leg."""
    return adopt_source(standard, tmp_path_factory.mktemp("against"),
                        {EXAMPLES: ("spec", EXAMPLES_ANSWER),
                         **RULES_IN_CODE},
                        {DOCS: ("spec", "code", DOCS_ANSWER)})


@pytest.fixture
def against_clone(adopted_against_a_rule, tmp_path) -> Path:
    """A private, mutable copy of that clone."""
    target = tmp_path / "Northwind"
    shutil.copytree(adopted_against_a_rule["clone"], target, symlinks=True)
    return target


@needs_filter_repo
def test_an_adoption_answered_against_a_rule_is_compliant_on_first_run(
        standard, adopted_against_a_rule):
    """L1-57, END TO END. The split's manifest records `docs/` in the code
    leg with the plan's reason, and the doctor's first run, which said
    `MISPLACED (1 path)` on main, reads the adoption COMPLIANT with the row
    `ok`. The block's comment says what a directory's row answers (L1-59).
    """
    clone = adopted_against_a_rule["clone"]
    text = (clone / "project.yaml").read_text(encoding="utf-8")
    manifest = parse_yaml(text)
    commit = adopted_against_a_rule["commit"]
    assert manifest["answered_paths"] == [
        {"path": DOCS, "leg": "code", "resolution": DOCS_ANSWER,
         "source_commit": commit},
        {"path": EXAMPLES, "leg": "spec", "resolution": EXAMPLES_ANSWER,
         "source_commit": commit}], manifest["answered_paths"]
    assert LATER in said(text), text
    result, verdict, row = placement(standard, clone)
    assert result.returncode == 0, result.stdout + result.stderr
    assert (verdict, row["status"]) == (COMPLIANT, "ok"), row
    assert [item["path"] for item in row["detail"]["answered_paths"]] == [
        "spec/examples/", DOCS_IN_CODE], row["detail"]


# --- L1-56: an emptied `.gitmodules` asks nothing ---------------------------

@pytest.mark.parametrize("body, asked", [
    ("", False), ("\n", True), ("# no submodule here\n", True)],
    ids=["no-byte", "a-blank-line", "a-comment"])
def test_an_empty_gitmodules_is_asked_nothing(standard, project, body,
                                              asked):
    """A `.gitmodules` that holds no byte registers no submodule, so the
    policy's question of it -- which leg owns the submodules it registers
    -- has nothing to ask: no question, the row `ok`, and said. One holding
    anything at all is a file only git's own reader can say registers
    nothing, and it stays the question it was."""
    stage(project / "code", GITMODULES, body)
    result, verdict, row = placement(standard, project)
    assert result.returncode == 0, result.stdout + result.stderr
    assert verdict == COMPLIANT
    questions = [item["path"] for item in row["detail"]["review_required"]]
    assert questions == (["code/.gitmodules"] if asked else []), row
    assert row["status"] == ("note" if asked else "ok"), row
    assert leg_entry(row, "code").get("empty_gitmodules") == (
        None if asked else ["code/.gitmodules"]), leg_entry(row, "code")
    clause = ("the policy asks nothing of 1 `.gitmodules` that hold(s) no "
              "byte and so register(s) no submodule (#655): code/.gitmodules")
    assert (clause in row["reason"]) != asked, row["reason"]


@pytest.fixture
def rules_removed(against_clone) -> Path:
    """The code leg's only submodule removed as `git rm` does it: its
    `.gitmodules` left tracked and empty."""
    leg = against_clone / "code"
    git("rm", "-q", RULES_PATH, cwd=leg)
    assert (leg / GITMODULES).read_bytes() == b""
    return against_clone


@needs_filter_repo
def test_a_leg_whose_only_submodule_was_removed_is_asked_nothing(
        standard, adopted_against_a_rule, rules_removed):
    """L1-56, END TO END. After `git rm` of the rules the record's row is
    the `note` #525 made it, and the emptied `.gitmodules` is no question;
    with the row deleted by hand, the placement row is `ok`."""
    result, verdict, row = placement(standard, rules_removed)
    assert result.returncode == 0, result.stdout + result.stderr
    assert (verdict, row["status"]) == (COMPLIANT, "note"), row
    assert row["detail"]["review_required"] == [], row["detail"]
    assert [item["path"] for item in row["detail"]["unheld"]] == [RULES_PATH]
    edit_manifest(rules_removed,
                  the_rules_row(adopted_against_a_rule["commit"]), "")
    result, verdict, row = placement(standard, rules_removed)
    assert result.returncode == 0, result.stdout + result.stderr
    assert (verdict, row["status"]) == (COMPLIANT, "ok"), row
    assert leg_entry(row, "code")["empty_gitmodules"] == ["code/.gitmodules"]


# --- L1-58: a directory's row without its `/` --------------------------------

@pytest.mark.parametrize("golden, rows, named, status", [
    (True, (("examples", "spec", EXAMPLES_ANSWER),), ["spec/examples"],
     "note"),
    (False, (("src", "code", "the code"),), ["code/src"], "ok"),
    (True, (("examples/golden/case.json", "spec"),
            ("examples/golden/case.expected.json", "spec")), [], "ok"),
    (True, (("examples", "code", EXAMPLES_ANSWER),), [], "note"),
], ids=["a-question-under-it", "nothing-asked-under-it", "file-rows",
        "a-row-for-the-other-leg"])
def test_a_directory_row_without_its_slash_is_said(standard, project, golden,
                                                   rows, named, status):
    """`_covering` reads a row without its `/` as a file's, so `examples`
    answers nothing under the spec leg's `examples/`: the question stays,
    and the leg's entry and the row now say why. Said, and never read as
    the directory's row nor made a finding: under a directory nothing asks
    about, such a row leaves the row `ok`. File rows are not named, nor is
    a row for a leg that holds no such directory."""
    if golden:
        golden_run(project)
    record_answers(project, *rows)
    result, verdict, row = placement(standard, project)
    assert result.returncode == 0, result.stdout + result.stderr
    assert verdict == COMPLIANT
    named_here = [path for leg in row["detail"]["legs"]
                  for path in leg.get("unslashed") or []]
    assert named_here == named, row["detail"]["legs"]
    assert row["status"] == status, row
    clause = [f"1 row(s) of project.yaml's `answered_paths:` name a "
              f"directory without the `/` a directory's row ends with, so "
              f"each answers nothing under it (#655): {path}"
              for path in named]
    assert [text for text in clause if text in row["reason"]] == clause, \
        row["reason"]
    assert ("without the `/`" in row["reason"]) == bool(named), row["reason"]


# --- L1-59: what a directory's row answers is said where it is read ---------

def test_a_directory_row_answers_a_file_added_later_and_says_so(standard,
                                                                project):
    """BY DESIGN: `source_commit:` is never consulted, so a file added under
    an answered directory after the adoption is answered by its row. The
    block `execute` writes, and the validator a project runs over it, now
    say so."""
    golden_run(project)
    stage(project / "spec", "examples/later/notes.txt", "added later\n")
    record_answers(project, (EXAMPLES, "spec", EXAMPLES_ANSWER))
    row = placement(standard, project)[2]
    assert (row["status"], row["detail"]["review_required"]) == ("ok", []), \
        row
    adopt = adoption_module(standard)
    block = adopt.answered_path_record(
        adopt.PathPolicy.load(adopt.PATH_POLICY),
        [{"path": EXAMPLES, "leg": "spec"}],
        tree_of(("examples/a/case.json", BLOB)), SOURCE_COMMIT)
    assert LATER in said(block), block
    validator = (REPO / "templates" / "assembly-root" / "scripts"
                 / "validate-manifest.py").read_text(encoding="utf-8")
    assert LATER in said(validator)


def test_agents_md_says_the_record_holds_answers_against_a_rule():
    """The one line AGENTS.md gives the record says what it now holds."""
    text = said((REPO / "AGENTS.md").read_text(encoding="utf-8"))
    assert ("`answered_paths:` (per other path the policy asked about or put "
            "elsewhere). They confer nothing; no command rewrites them.") \
        in text
