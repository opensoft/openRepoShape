"""A plan's answer against a rule is recorded, an emptied `.gitmodules` asks
nothing, and a record's row says what it answers (#655: #457's L1-56 and
L1-57, with L1-58 and L1-59 riding along).

THE DEFECTS, on main a5245427:

  * L1-57. `docs/` (rule `spec-governance`) answered `code` in the plan
    passed `check`, and `execute` said `adoption verified`. The doctor's
    first run then said `MISPLACED (1 path)`, exit 1: `answered_paths:`
    (#525) recorded the plan's answers to the policy's questions only, so
    its answer against a rule the policy named was written nowhere.
  * L1-56. `git rm` of a leg's only submodule leaves that leg's
    `.gitmodules` tracked and 0 bytes. Rule `ambiguous-gitmodules` asked
    about it on every run, and no record could answer it.
  * L1-58. A hand-written `answered_paths:` row `examples` -- a directory,
    without the `/` a directory's row ends with -- passed the validator and
    settled nothing, and nothing said so.
  * L1-59. A directory's row also answers a file added under it after the
    adoption, and nothing a reader of the row sees said so.

THE FIX. `execute` records each entry the plan keeps in a leg that covers a
path the policy's walk does not put in that leg: a question, as before, or a
path a rule puts in the other leg or the root. The doctor takes a row as the
answer for a path in the wrong leg as it does for a question, file by file
and only in the leg the row names. An empty `.gitmodules` registers no
submodule, so the doctor asks nothing of it and says so. A row naming a
directory of its leg without its `/` is said. The block's own comment, and
the project's validator, say that a directory's row answers files added
later too.
"""

